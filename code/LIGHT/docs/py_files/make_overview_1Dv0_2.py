def _m(name):
    """1Dv0_2's modules ('1Dv0_2' is not an identifier)."""
    return importlib.import_module(f"1Dv0_2.{name}")


def _md5(path: Path) -> str:
    return hashlib.md5(path.read_bytes()).hexdigest()


def _sci(x: float, digits: int = 1) -> str:
    """A small relative number as LaTeX, 1.5e-05 -> 1.5\\times10^{-5}."""
    if x == 0.0:
        return "0"
    mant, ex = f"{x:.{digits}e}".split("e")
    return f"{mant}{{\\times}}10^{{{int(ex)}}}"


def _pow10_above(x: float) -> str:
    """The smallest power of ten at or above x, as LaTeX (an upper bound)."""
    return f"10^{{{math.ceil(math.log10(x))}}}" if x > 0 else "0"


def _render(n: dict, what: str, tables=()) -> str:
    v1 = importlib.import_module("1Dv0_2").__version__
    lines = [
        f"% LIGHT 1Dv0_2 accuracy numbers ({what}). GENERATED by "
        "make_overview_1Dv0_2.py",
        f"% from LIGHT 1Dv0_2 ({v1}) on Fluid1D. Do not edit. Rerun the "
        "script instead.",
        r"\providecommand\didef[2]{\expandafter\def\csname di@#1\endcsname{#2}}",
    ]
    lines += [f"\\didef{{{k}}}{{{v}}}" for k, v in n.items()]
    lines += list(tables)
    return "\n".join(lines) + "\n"


