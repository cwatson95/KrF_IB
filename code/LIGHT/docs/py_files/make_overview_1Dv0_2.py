def chemistry_files() -> tuple:
    """The files that make up 1Dv0_2's chemistry: sim1d's list (which its
    runs record) and the report."""
    return tuple(_m("sim1d").CHEMISTRY_FILES) + ("report.py",)


def check_chemistry() -> dict:
    """md5 of every chemistry file in 1Dv0_2 against v0_2's. Raises if one
    differs: then v0_2's scores are not 1Dv0_2's."""
    one, two = LIGHT / "1Dv0_2", LIGHT / VERSION
    bad = [f for f in chemistry_files() if _md5(one / f) != _md5(two / f)]
    if bad:
        raise RuntimeError(f"1Dv0_2's {bad} differ from {VERSION}'s: the v0_2 "
                           "overview's scores are no longer 1Dv0_2's")
    return {f: _md5(one / f) for f in chemistry_files()}


def _random_state(chem, bridge, cells, seed):
    """test_1d.py's random cell states: every species over seven decades,
    Tg 250-1500 K, the mean energy from the floor to 50 eV."""
    rng = np.random.default_rng(seed)
    n_gas = 2.45e25
    dens = np.zeros((cells, chem.n_real))
    dens[:, chem.col["Kr"]] = n_gas * 0.995
    dens[:, chem.col["F2"]] = n_gas * 10 ** rng.uniform(-5, -2.3, cells)
    for s in chem.heavy:
        if s not in ("Kr", "F2"):
            dens[:, chem.col[s]] = 10 ** rng.uniform(*RANDOM_LOG_N, cells)
    dens[:, chem.e_col] = 10 ** rng.uniform(*RANDOM_LOG_N, cells)
    tg = rng.uniform(*RANDOM_TG, cells)
    eps = 10 ** rng.uniform(math.log10(bridge.EPS_LO),
                            math.log10(RANDOM_EPS_HI), cells)
    return dens, tg, eps


def rate_deviations() -> dict:
    """The stage's rate of every row against v0_2's Model._k at random cell
    states, with the bands at their defaults and with the three unmeasured
    ones set (so every band row runs at a nonzero rate): the largest
    relative deviation of the rows that depend on Tg and densities, of the
    Te-table rows inside v0_2's table (to xsec.TE_MAX) and above it, and of
    the two-temperature tail, and the compiled kernel against the Python
    rates.

    Above TE_MAX the stage holds every table row at its edge value. v0_2's
    cross-section tables do the same, but Model._k evaluates a power-law
    row (te_pow, Kr2+ + e) at any Te, so there the two differ. The script
    names the rows that do and raises if one is not a power law, since the
    overview's text says which."""
    bridge, model, xsec = _m("fluid1d"), _m("model"), _m("xsec")
    worst = {"static": 0.0, "table": 0.0, "above": 0.0, "tail": 0.0}
    te_table_worst, above_rows = 0.0, set()
    kern_worst, n_points = 0.0, 0
    for i, rates in enumerate(((), BANDS_SET)):
        chem = bridge.CellChemistry(model.Model(model.Params(rates=rates)))
        dens, tg, eps = _random_state(chem, bridge, N_RANDOM, seed=11 + i)
        k_static = chem.static_rates(tg, dens)
        log_r = chem.tail_log_ratio(dens)
        k_tab = chem.table_rates(eps, log_r)
        m = chem.model
        for c in range(dens.shape[0]):
            n0 = dens[c, 1:] * 1e-6
            te = eps[c] / 1.5
            for r, comp in enumerate(chem.rows):
                ref = m._k(comp, te, tg[c], n0, dens[c, 0] * 1e-6) \
                    * chem.si[r]
                kind = int(chem.kind[r])
                got = k_static[c, r] if kind == 0 else k_tab[c, r]
                if ref <= xsec._K_FLOOR * chem.si[r] * (1 + 1e-12):
                    if got > ref:
                        raise AssertionError(f"{comp.row.rid}: above the "
                                             "floor where Model._k is not")
                    continue
                dev = abs(got / ref - 1.0)
                n_points += 1
                if kind == 0:
                    worst["static"] = max(worst["static"], dev)
                elif kind == 2:
                    worst["tail"] = max(worst["tail"], dev)
                elif te > xsec.TE_MAX:
                    worst["above"] = max(worst["above"], dev)
                    if dev > 1e-9:
                        above_rows.add((comp.row.rid, comp.kind))
                elif dev > worst["table"]:
                    worst["table"], te_table_worst = dev, te
        kern = bridge.kernel_rates(chem, eps, k_static, log_r)
        tot = k_static + k_tab
        mask = tot > 0
        kern_worst = max(kern_worst, float(np.max(np.abs(
            kern[mask] / tot[mask] - 1.0))))
    if {kind for _, kind in above_rows} - {"te_pow"}:
        raise AssertionError(f"rows other than power laws differ above the "
                             f"table's edge: {sorted(above_rows)}")
    # the power law's excess at the mean-energy ceiling, where the stage
    # holds the value at TE_MAX: (Te_ceiling / TE_MAX)^(-n)
    rows = {c.row.rid: c.row for c in model.Model(model.Params()).compiled}
    ceiling = {}
    for rid, _ in sorted(above_rows):
        n_pow = rows[rid].rate[3]
        ceiling[rid] = (bridge.EPS_HI / 1.5 / xsec.TE_MAX) ** (-n_pow) - 1.0
    (rid, excess), = ceiling.items()

    def agree(dev):
        """'exactly', or 'to <dev>', as the text prints an agreement."""
        return "exactly" if dev == 0.0 else f"to ${_sci(dev)}$"
    return {"rates.static": agree(worst["static"]),
            "rates.table": _sci(worst["table"]),
            "rates.table.te": f"{te_table_worst:.3g}",
            "rates.above": f"{100 * worst['above']:.0f}",
            "rates.above.row": rid.replace("_", r"\_"),
            "rates.above.ceiling": f"{100 * excess:.0f}",
            "rates.temax": f"{xsec.TE_MAX:g}",
            "rates.tail": _sci(worst["tail"]),
            "rates.kernel": agree(kern_worst),
            "rates.n": f"{n_points:,}".replace(",", "{,}"),
            "rates.cells": str(2 * N_RANDOM)}


def _tt_path(path: str) -> str:
    """A path in typewriter type that may break after each '/'."""
    parts = path.replace("_", r"\_").split("/")
    return r"/\allowbreak".join(r"\texttt{" + p + "}" for p in parts)


def fast_numbers() -> tuple:
    bridge = _m("fluid1d")
    bridge.load()
    md5 = check_chemistry()
    v02 = importlib.import_module(VERSION)
    n = {"version": importlib.import_module("1Dv0_2").__version__,
         "chem.version": v02.__version__,
         "chem.nfiles": str(len(md5)),
         "chem.files": ", ".join(_tt_path(f) for f in md5),
         "eps.lo": f"{bridge.EPS_LO:g}", "eps.hi": f"{bridge.EPS_HI:g}",
         "te.lo": f"{bridge.EPS_LO / 1.5:.2g}",
         "te.hi": f"{bridge.EPS_HI / 1.5:.0f}",
         "substep.change": f"{100 * bridge.SUBSTEP_CHANGE:.0f}",
         "substep.max": str(bridge.MAX_SUBSTEPS),
         # where Fluid1D lives beside LIGHT (FLUID1D_SRC may point to
         # another copy of the same files, which the 1-D tests hash)
         "fluid1d.src": _tt_path(str(bridge.DEFAULT_SRC.relative_to(
             LIGHT.parent)))}
    n.update(rate_deviations())
    # the settings of the runs and the random states, as the text cites
    # them
    n.update({"rates.tg.lo": f"{RANDOM_TG[0]:.0f}",
              "rates.tg.hi": f"{RANDOM_TG[1]:.0f}",
              "rates.te.hi": f"{RANDOM_EPS_HI / 1.5:.0f}",
              "rates.decades": str(RANDOM_LOG_N[1] - RANDOM_LOG_N[0]),
              "set.band.cells": str(BAND_CELLS),
              "set.tahoma.cells": str(TAHOMA_CELLS)})
    for i, cells in enumerate(MESHES, 1):
        n[f"set.mesh.{i}"] = str(cells)
    for i, dt in enumerate(DT_LADDER, 1):
        n[f"set.dt.{i}"] = f"{dt * 1e12:g}"
    return n, []


