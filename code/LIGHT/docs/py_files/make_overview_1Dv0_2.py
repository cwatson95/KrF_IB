def _run(p):
    return _m("sim1d").run(p)


def _share(res, band, where):
    """Percent of the input radiated in one band, gap or centre cell."""
    led = res.data["records"][-1][where]
    return 100.0 * led[f"rad:{band}"] / led["input"]


B248, B147 = "248 nm (KrF B-X)", "147 nm (Kr2* VUV)"


def reference_ladder(out: str) -> tuple:
    """v0_2's reference point on each mesh: the centre cell against v0_2's
    0-D run, the gap, the wall cells, the walls and the ledger."""
    sim1d, model, report = _m("sim1d"), _m("model"), _m("report")
    n, rows, runs = {}, [], {}
    base = sim1d.Params1D(threads=THREADS, verbose=False, output_dir=out)
    d0 = report.row_dict(model.run(base.cell_params()))
    n["ref.0d.248"] = f"{d0['emission_248']:.5f}"
    n["ref.0d.147"] = f"{d0['emission_vuv']:.4f}"
    n["ref.0d.tg"] = f"{d0['tg_end_K']:.2f}"
    dev248, dev147, devtg, dev_int = 0.0, 0.0, 0.0, 0.0
    deficit = {}
    for cells in MESHES:
        res = _run(base.replace(cells=cells, name=f"ref{cells}"))
        runs[cells] = res
        fate = res.fate()
        c248 = res.share_248("ledger_centre")
        c147 = _share(res, B147, "ledger_centre")
        g248 = res.share_248("ledger")
        last = res.data["records"][-1]
        e_in = last["ledger"]["input"]
        dev248 = max(dev248, abs(c248 / d0["emission_248"] - 1.0))
        dev147 = max(dev147, abs(c147 / d0["emission_vuv"] - 1.0))
        devtg = max(devtg, abs(last["tg_centre"] / d0["tg_end_K"] - 1.0))
        deficit[cells] = d0["emission_248"] - g248
        # each cell's own 248-nm share: the cell beside the wall cell, how
        # far from the wall the cells differ from the centre by more than
        # NEAR_WALL, and the interior beyond INTERIOR_CM
        led = res.data["ledger_cells"]
        share = 100.0 * np.array(led[f"rad:{B248}"]) / np.array(led["input"])
        rel = np.abs(share / share[cells // 2] - 1.0)
        x = res.x_cm
        near = np.nonzero(rel[:cells // 2] > NEAR_WALL)[0]
        reach = (float(x[near[-1]]) + 0.5 * p_dx(res)) if near.size else 0.0
        inner = (x > INTERIOR_CM) & (x < res.p["gap_cm"] - INTERIOR_CM)
        dev_int = max(dev_int, float(np.max(rel[inner])))
        k = f"ref.{cells}"
        n[f"{k}.c248"] = f"{c248:.5f}"
        n[f"{k}.g248"] = f"{g248:.3f}"
        n[f"{k}.g147"] = f"{_share(res, B147, 'ledger'):.2f}"
        n[f"{k}.cut"] = f"{fate['cut by the mean-energy bounds']:.2f}"
        n[f"{k}.walls"] = f"{fate['lost to the walls']:.3f}"
        n[f"{k}.phantom"] = f"{-100 * res.data['field_dropped'] / e_in:.2f}"
        n[f"{k}.tg"] = f"{last['tg_mean']:.0f}"
        n[f"{k}.second"] = f"{share[1]:.3f}"
        n[f"{k}.reach"] = f"{reach * 1e4:.0f}"
        rows.append(f"{cells} & {c248:.5f} & {share[1]:.3f} & {g248:.3f} & "
                    f"{fate['cut by the mean-energy bounds']:.2f} & "
                    f"{-100 * res.data['field_dropped'] / e_in:.2f} & "
                    f"{fate['lost to the walls']:.3f} & "
                    f"{last['tg_mean']:.0f}\\\\")
    n["ref.dev.248"] = f"${_sci(dev248)}$"
    n["ref.dev.147"] = f"${_sci(dev147)}$"
    n["ref.dev.tg"] = f"${_sci(devtg)}$"
    n["int.cm"] = f"{INTERIOR_CM:g}"
    n["int.dev"] = f"${_sci(dev_int)}$"
    n["near.tol"] = f"$10^{{{int(round(math.log10(NEAR_WALL)))}}}$"
    worst_closure = max(abs(r.fate()["closure residual"]) / 100
                        for r in runs.values())
    n["ref.closure"] = f"${_pow10_above(worst_closure)}$"
    # the gap average approaches the interior first order in dx: its
    # deficit halves with each doubling of the mesh
    ratios = [deficit[a] / deficit[b] for a, b in zip(MESHES, MESHES[1:])]
    n["mesh.ratio.lo"] = f"{min(ratios):.2f}"
    n["mesh.ratio.hi"] = f"{max(ratios):.2f}"
    n["mesh.lo"], n["mesh.hi"] = str(MESHES[0]), str(MESHES[-1])
    n["ref.pulse"] = f"{base.pulse_s * 1e6:g}"
    n["ref.tend"] = f"{base.t_end_s * 1e6:g}"
    n["ref.gap"] = f"{base.gap_cm:g}"
    n["ref.dt"] = f"{base.dt_s * 1e12:g}"
    n["ref.P"] = f"{base.power_W_cm3 / 1e3:.0f}"
    n["ref.p"] = f"{base.pressure_atm:g}"
    n["ref.xF2"] = f"{100 * base.x_f2:g}"
    n["ref.seed"] = f"${_k(base.ne_cm3)}$"
    # the finest mesh against the sheath it cannot resolve: its cell size
    # and the Debye length in the centre cell at mid-pulse
    fine = runs[MESHES[-1]]
    prof = min(fine.data["profiles"],
               key=lambda q: abs(q["t"] - 0.5 * fine.p["pulse_s"]))
    mid = MESHES[-1] // 2
    ne = prof["dens"][fine.species.index("e-")][mid] * 1e6      # m^-3
    te = prof["te"][mid]                                        # eV
    debye = math.sqrt(8.8541878128e-12 * te / (ne * 1.602176634e-19))
    n["debye.um"] = f"{debye * 1e6:.1f}"
    n["cell.um"] = f"{p_dx(fine) * 1e4:.0f}"
    tables = ["\\def\\diMesh{" + "\n".join(rows) + "}",
              _profiles(runs)]
    return n, tables


def p_dx(res) -> float:
    """A run's cell size [cm]."""
    return res.p["gap_cm"] / res.p["cells"]


def _profiles(runs) -> str:
    """The gap figure's data: each mesh's local 248-nm share of the cell's
    input across the gap, and the finest mesh's n_e and T_e at mid-pulse.
    pgfplots coordinates, in macros."""
    out = []
    for cells, res in runs.items():
        led = res.data["ledger_cells"]
        share = 100.0 * np.array(led[f"rad:{B248}"]) / np.array(led["input"])
        x = res.x_cm
        pts = " ".join(f"({xi:.5f},{si:.4f})" for xi, si in zip(x, share))
        out.append(f"\\def\\diProf{_alpha(cells)}{{{pts}}}")
    fine = runs[MESHES[-1]]
    pulse = fine.p["pulse_s"]
    prof = min(fine.data["profiles"], key=lambda q: abs(q["t"] - 0.5 * pulse))
    e = fine.species.index("e-")
    ne = np.array(prof["dens"][e])
    te = np.array(prof["te"])
    x = fine.x_cm
    out.append("\\def\\diNe{" + " ".join(
        f"({xi:.5f},{ni:.4e})" for xi, ni in zip(x, ne)) + "}")
    out.append("\\def\\diTe{" + " ".join(
        f"({xi:.5f},{ti:.4f})" for xi, ti in zip(x, te)) + "}")
    out.append(f"\\didef{{prof.t}}{{{prof['t'] * 1e9:.0f}}}")
    return "\n".join(out)


def _alpha(cells: int) -> str:
    """Macro names cannot hold digits: 32 -> A, 64 -> B, ..."""
    return "ABCDEFG"[MESHES.index(cells)]


def band_top(out: str) -> dict:
    """Kr2* + F at the top of its band on 64 cells: the centre cell against
    v0_2's 0-D run with the same band."""
    sim1d, model, report = _m("sim1d"), _m("model"), _m("report")
    p = sim1d.Params1D(cells=BAND_CELLS, rates=BAND_TOP, threads=THREADS,
                       verbose=False, output_dir=out, name="band_top")
    res = _run(p)
    d0 = report.row_dict(model.run(p.cell_params()))
    c248 = res.share_248("ledger_centre")
    c147 = _share(res, B147, "ledger_centre")
    return {"band.k": f"${_k(BAND_TOP[0][1])}$",
            "band.c248": f"{c248:.5f}", "band.0d.248": f"{d0['emission_248']:.5f}",
            "band.c147": f"{c147:.3f}", "band.0d.147": f"{d0['emission_vuv']:.3f}",
            "band.dev": f"${_sci(abs(c248 / d0['emission_248'] - 1))}$",
            "band.tg": f"{res.data['records'][-1]['tg_centre']:.2f}",
            "band.0d.tg": f"{d0['tg_end_K']:.2f}"}


def time_step(out: str) -> dict:
    """test_1d.py's time-step check at three steps: a 20-ns pulse on 8
    cells, the centre cell's largest relative Te error against v0_2's 0-D
    run (the transient, since the steady state is exact)."""
    sim1d, model = _m("sim1d"), _m("model")
    p = sim1d.Params1D(**SHORT, threads=THREADS, verbose=False,
                       output_dir=out)
    r0 = model.run(p.cell_params().replace(n_save=4001))
    errs = []
    for dt in DT_LADDER:
        res = _run(p.replace(dt_s=dt, name=f"dt{dt * 1e15:.0f}"))
        te1 = np.array([r["te_centre"] for r in res.data["records"]])
        te0 = np.interp(res.t, r0.t, r0.te)
        errs.append(float(np.max(np.abs(te1[1:] / te0[1:] - 1))))
    n = {"dt.pulse": f"{SHORT['pulse_s'] * 1e9:g}",
         "dt.cells": str(SHORT["cells"])}
    for dt, e in zip(DT_LADDER, errs):
        n[f"dt.{dt * 1e12:g}"] = f"{100 * e:.1f}"
    n["dt.ratio.lo"] = f"{min(a / b for a, b in zip(errs, errs[1:])):.2f}"
    n["dt.ratio.hi"] = f"{max(a / b for a, b in zip(errs, errs[1:])):.2f}"
    return n


def tahoma(out: str) -> tuple:
    """Tahoma on 1Dv0_2's own power input with ML's constants imposed (the
    way the v0_2 overview scores v0_2's own input): the centre cell's and
    the gap's g0 over ML's window against v0_2's 0-D run, from two seeds
    that break down and from ML's own seed, which does not."""
    import ml
    if ml.LIGHT_VERSION != VERSION:
        raise RuntimeError(f"ML runs LIGHT {ml.LIGHT_VERSION}: run this "
                           "script as a program (main() sets LIGHT_VERSION)")
    from ml import data, forward, params
    sim1d, model, bridge = _m("sim1d"), _m("model"), _m("fluid1d")
    from Fluid1D import Numerics
    c = forward.with_rederived_k_e(params.light_now())
    meas = data.by_name("tahoma_g0")[0].values[0]
    lo, hi = forward.WINDOW
    n, rows = {}, []
    for seed in TAHOMA_SEEDS + (ML_SEED,):
        p0 = forward.tahoma_params().replace(ne_cm3=seed)
        # v0_2's 0-D run, with 1Dv0_2's own copy of the model
        m0 = forward.impose(model.Model(model.Params(**{
            f: getattr(p0, f) for f in p0.__dataclass_fields__})), c)
        r0 = m0.run()
        win = (r0.t >= lo) & (r0.t <= hi)
        g0_0d = forward.SIGMA_B * float(np.mean(r0.n["KrF(B)"][win])) * 100.0
        te_max = float(r0.te.max())
        p1 = sim1d.Params1D(pressure_atm=p0.pressure_atm, x_f2=p0.x_f2,
                            power_W_cm3=p0.power_W_cm3, pulse_s=p0.pulse_s,
                            t_end_s=p0.t_end_s, ne_cm3=seed, groups=p0.groups,
                            rates=p0.rates, cells=TAHOMA_CELLS,
                            n_save=p0.n_save, n_profiles=3, threads=THREADS,
                            verbose=False, output_dir=out,
                            name=f"tahoma_{seed:.0e}")
        sim = sim1d.simulation_class()(p1)
        forward.impose(sim.cell_model, c)
        sim.chem = bridge.CellChemistry(sim.cell_model)
        sim.run(Numerics(steps=int(round(p1.t_end_s / p1.dt_s)), dt=p1.dt_s,
                         fluid_every=max(1, int(round(1e-9 / p1.dt_s))),
                         fluid_substeps=1, field_heating_cap_factor=None,
                         electron_energy_closure="source_coupled"),
                verbose=False)
        res = sim1d.Result1D.from_simulation(sim, 0.0)
        w1 = (res.t >= lo) & (res.t <= hi)
        g_c = forward.SIGMA_B * float(res.series("KrF(B)", "centre")[w1].mean()) \
            * 100.0
        g_g = forward.SIGMA_B * float(res.series("KrF(B)", "mean")[w1].mean()) \
            * 100.0
        cut = res.fate()["cut by the mean-energy bounds"]
        k = "ml" if seed == ML_SEED else f"s{int(round(math.log10(seed)))}"
        n[f"tah.{k}.seed"] = f"$10^{{{int(round(math.log10(seed)))}}}$"
        n[f"tah.{k}.0d"] = f"{g0_0d:.3f}"
        n[f"tah.{k}.0d.x"] = f"{g0_0d / meas:.3f}"
        n[f"tah.{k}.0d.temax"] = f"{te_max:.0f}"
        n[f"tah.{k}.c"] = f"{g_c:.3f}"
        n[f"tah.{k}.c.x"] = f"{g_c / meas:.3f}"
        n[f"tah.{k}.g"] = f"{g_g:.2f}"
        n[f"tah.{k}.g.x"] = f"{g_g / meas:.2f}"
        if seed != ML_SEED:
            # a seed that breaks down: the centre cell is the 0-D run
            n[f"tah.{k}.dev"] = f"${_sci(abs(g_c / g0_0d - 1))}$"
        n[f"tah.{k}.cut"] = f"{cut:.1f}"
        rows.append(f"{n[f'tah.{k}.seed']} & {g0_0d:.3f} & {g_c:.3f} & "
                    f"{g_g:.2f} & {cut:.1f}\\\\")
    n["tah.meas"] = f"{meas:.2f}"
    n["tah.cells"] = str(TAHOMA_CELLS)
    n["tah.torr"] = f"{forward.TAHOMA_COND['pressure_torr']:.0f}"
    n["tah.f2torr"] = f"{forward.TAHOMA_COND['f2_torr']:.1f}"
    n["tah.pin"] = f"{forward.TAHOMA_COND['power_W_cm3'] / 1e3:.0f}"
    n["tah.pulse"] = f"{forward.TAHOMA_COND['pulse_s'] * 1e9:.0f}"
    n["tah.win.lo"] = f"{lo * 1e9:.0f}"
    n["tah.win.hi"] = f"{hi * 1e9:.0f}"
    n["tah.te.cap"] = f"{bridge.EPS_HI / 1.5:.0f}"
    return n, ["\\def\\diTahoma{" + "\n".join(rows) + "}"]


def slow_numbers() -> tuple:
    n, tables = {}, []
    with tempfile.TemporaryDirectory(prefix="overview_1Dv0_2_") as out:
        for part in (reference_ladder, tahoma):
            nn, tt = part(out)
            n.update(nn)
            tables += tt
        n.update(band_top(out))
        n.update(time_step(out))
    return n, tables


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--fast", action="store_true",
                    help="write the fast file only")
    ap.add_argument("--check", choices=("fast", "slow"),
                    help="compare one file with a fresh run, write nothing")
    a = ap.parse_args(argv)
    # before ML is imported anywhere in this process
    os.environ["LIGHT_VERSION"] = VERSION
    if sys.version_info < (3, 11):
        raise SystemExit("Fluid1D needs Python >= 3.11 with numba: run this "
                         "with ~/.venvs/f2sweep/bin/python")
    if a.check:
        fresh = {"fast": lambda: _render(*_fast()),
                 "slow": lambda: _render(*_slow())}[a.check]()
        path = {"fast": OUT_FAST, "slow": OUT_SLOW}[a.check]
        if path.read_text() != fresh:
            print(f"{path.name} is stale: rerun make_overview_1Dv0_2.py")
            return 1
        print(f"{path.name} is current")
        return 0
    OUT_FAST.write_text(_render(*_fast()))
    print(f"wrote {OUT_FAST}", flush=True)
    if not a.fast:
        OUT_SLOW.write_text(_render(*_slow()))
        print(f"wrote {OUT_SLOW}")
    return 0


def _fast():
    n, tables = fast_numbers()
    return n, "fast", tables


def _slow():
    n, tables = slow_numbers()
    return n, "slow", tables


if __name__ == "__main__":
    sys.exit(main())
