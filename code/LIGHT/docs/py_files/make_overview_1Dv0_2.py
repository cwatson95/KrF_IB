"""Numbers, tables and profiles for accuracy_overview_1Dv0_2.tex, the 1-D
model's accuracy.

1Dv0_2 runs v0_2's chemistry, file for file, in every cell of a gap on
Fluid1D. So the scores of its chemistry are v0_2's, which
make_overview_v0_2.py writes (overview_v0_2_*.tex, the v0_2 overview),
and the 1-D overview reads them from there. This script first proves that
the chemistry files are v0_2's (their md5 sums), and refuses to write
anything if one differs. Then it writes what the 1-D layer adds, each
number a \\didef{key}{value} or a finished table (a macro of its own, so
the document holds v0_2's numbers and 1Dv0_2's):

  overview_1Dv0_2_fast.tex  seconds: the chemistry files against v0_2's,
                            and every rate the stage computes against
                            v0_2's Model._k at random cell states
  overview_1Dv0_2_slow.tex  minutes: v0_2's reference point on 32 to 256
                            cells (the centre cell against v0_2's 0-D run,
                            the gap average, the wall cells, the energy to
                            the walls, the ledger), Kr2* + F at the top of
                            its band, the time step, Tahoma on 1Dv0_2's own
                            power input (the centre cell against v0_2's, and
                            the seed it needs), and the profiles the gap
                            figure draws

Fluid1D needs Python >= 3.11 with numba, and ML (for Tahoma's constants)
runs v0_2 in the same process (LIGHT_VERSION=v0_2, set in main()). Runs
use four numba threads.

    PY=~/.venvs/f2sweep/bin/python
    $PY LIGHT/docs/make_overview_1Dv0_2.py              # both, ~10 min
    $PY LIGHT/docs/make_overview_1Dv0_2.py --fast       # the fast file
    $PY LIGHT/docs/make_overview_1Dv0_2.py --check fast # compare only
    cd LIGHT/docs && latexmk -pdf accuracy_overview_1Dv0_2.tex
"""

