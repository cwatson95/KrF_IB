def _krf_decay(kr_torr, f2_torr):
    """KrF(B) seeded in Kr/F2 at 300 K with no power, under v0_3's own
    closure (the kinetic EEDF, which a seed of 1 electron per cm3 leaves to
    the Maxwellian), and the slow decay of KrF(B) + KrF(C) fitted."""
    from v0_3.model import Model, Params
    tot = kr_torr + f2_torr
    p = Params(pressure_atm=tot / 760.0, x_f2=f2_torr / tot,
               power_W_cm3=0.0, pulse_s=0.0, t_end_s=400e-9,
               ne_mode="free", ne_cm3=1.0, n_save=2001,
               init_extra_cm3=(("KrF(B)", 1e12),))
    r = Model(p).run()
    n = r.n["KrF(B)"] + r.n.get("KrF(C)", 0.0)
    rel = n / n[0]
    sel = (r.t > 20e-9) & (rel < 1e-3) & (rel > 1e-8)
    return -np.polyfit(r.t[sel], np.log(n[sel]), 1)[0]


def _solver_checks() -> dict:
    """The kinetic solver's checks of v0_3/tests/test_kinetic.py, as
    numbers: the same states and solvers."""
    sys.path.insert(0, str(LIGHT / "v0_3" / "tests"))
    from v0_3 import boltzmann as KB
    from v0_3 import xsec
    import test_kinetic as TK
    n = {}
    # ML's dense solver at three driven states, ML's e-e quadrature
    sys.path.insert(0, str(TK.ML_BOLTZ))
    import ee
    import gases_twin as GT
    GT.load_tables(str(TK.LOKI_INPUT))
    dF, dk, own = 0.0, 0.0, 0.0
    for xf2, en, ne_n, tg in ((0.005, 10.0, 1e-5, 300.0),
                              (0.0, 20.0, 3e-6, 300.0),
                              (0.02, 30.0, 1e-4, 600.0)):
        n_col, N, emax = 2.4e25, 600, 40.0
        kr, f2 = (GT.build("Kr", tg, str(TK.LOKI_INPUT)),
                  GT.build("F2", tg, str(TK.LOKI_INPUT)))
        mix = [(kr, 1.0 - xf2)] + ([(f2, xf2)] if xf2 > 0 else [])
        ml = ee.solve_field(mix, en, tg, N, emax, ne_N=ne_n,
                            ne_m3=ne_n * n_col, tol=1e-11)
        procs = [KB.Process(g, p.kind, p.threshold, p)
                 for g in ("Kr", "F2") for p in xsec.processes(g)
                 if p.kind in ("excitation", "ionization", "attachment")]
        st = KB.State(x={"Kr": 1.0 - xf2, "F2": xf2}, tg=tg, n_col=n_col,
                      ne=ne_n * n_col)
        mine = KB.Solver(procs, n_cells=N, emax=emax, tol=1e-11, maxit=4000,
                         ee_quadrature="cell").solve(st, en)
        dF = max(dF, float(np.max(np.abs(mine.F - ml["F"])) / ml["F"].max()))
        for gid, gas, thr in (("Kr", kr, 9.915), ("Kr", kr, 13.996),
                              ("F2", f2, 0.0), ("F2", f2, 3.16)):
            if gid == "F2" and xf2 == 0:
                continue
            c = next(c for c in gas["colls"] if abs(c["thr"] - thr) < 1e-6)
            p = next(q.p for q in procs if q.gas == gid
                     and abs(q.threshold - thr) < 1e-6)
            dk = max(dk, abs(mine.grid.rate(p, mine.F) / ee.rate(c, ml) - 1))
        ours = KB.Solver(procs, n_cells=N, emax=emax, tol=1e-11,
                         maxit=4000).solve(st, en)
        own = max(own, float(np.max(np.abs(ours.F - ml["F"]))
                             / ml["F"].max()))
    n["ml.dF"], n["ml.dk"], n["ml.own"] = _e(dF), _e(dk), _e(own)
    n["ml.states"] = "3"
    # the balances, LIGHT's configuration (Kr's elastic loss alone)
    procs = TK._procs()
    s = KB.Solver(procs, n_cells=600, emax=30.0, elastic=("Kr",))
    for key, st, target in (("pulse", TK._laser(1.9e7), 4.5),
                            ("nofield", TK._laser(2.1e7), None)):
        sol = s.eedf(st, target)
        gain, loss, nu = TK._energy(s, st, sol, procs)
        n[f"bal.{key}"] = _e(abs(loss - gain) / gain)
        n[f"bal.{key}.nu"] = _e(abs(sol.nu / nu - 1.0) if nu else 0.0)
    st = TK._laser(6.4e7)
    sol = s.eedf(st, 2.7)
    gain, loss, net = TK._energy(s, st, sol, procs)
    n["bal.nogrowth"] = _e(abs(loss - gain + net * sol.grid.ec[0]) / gain)
    n["bal.nogrowth.raw"] = _e(abs(loss - gain) / gain)
    # the undriven EEDF: the grid's Maxwellian at Tg, and ML's quadrature
    st = KB.State(x={"Kr": 1.0, "F2": 0.0}, tg=300.0, n_col=2.45e25,
                  ne=2.45e20)
    for cells in (600, 2400):
        good = KB.Solver(procs, n_cells=cells, emax=12.0).solve_joint(
            st, None, None, None, None, True)
        FM = good.grid.maxwellian(KB.KB * 300.0 / KB.QE)
        bulk = good.grid.ec < 0.5
        n[f"und.{cells}.dev"] = _e(float(np.max(np.abs(good.F[bulk]
                                                       / FM[bulk] - 1.0))))
        bad = KB.Solver(procs, n_cells=cells, emax=12.0,
                        ee_quadrature="cell").solve_joint(
            st, None, None, None, None, True)
        n[f"und.{cells}.cell"] = f"{bad.mean:.3f}"
        n[f"und.{cells}.mean"] = f"{good.mean:.4f}"
    n["und.32kt"] = f"{1.5 * KB.KB * 300.0 / KB.QE:.4f}"
    # the fixed-field S curve 0.12 ns into the reference pulse
    s12 = KB.Solver(procs, n_cells=600, emax=12.0, elastic=("Kr",))
    g = s12.grid

    def fixed(F0):
        sol = s12.solve_joint(TK.TRANSIENT, None, F0, None, None, False,
                              en_fixed=0.4)
        return sol or s12.solve_joint(TK.TRANSIENT, None, F0, None, None,
                                      False, en_fixed=0.4, m=0, maxit=3000)
    n["s.hot"] = f"{fixed(g.maxwellian(2.0)).mean:.3f}"
    n["s.cold"] = f"{fixed(g.maxwellian(0.026)).mean:.3f}"
    for t, key in ((0.06, "006"), (0.2, "02"), (0.5, "05")):
        sol = s12.solve_joint(TK.TRANSIENT, t, None, None, None, False)
        n[f"s.en.{key}"] = f"{sol.en_td:.3f}"
    # the beam's secondaries on three grids
    dev = max(abs(float(np.sum(KB.Grid(600, e, procs).injection(9.915, 4.506)
                               * KB.Grid(600, e, procs).ec)) / 4.506 - 1.0)
              for e in (12.0, 21.26, 40.0))
    n["inj.dev"] = _e(dev)
    # the time step: its two limits, its energy without e-e, and the flux
    # scheme's energy exchange with e-e at thermal energies, on 600 and
    # 2400 cells (test_time_step_limits_and_its_energy)
    s30 = KB.Solver(procs, n_cells=600, emax=30.0, elastic=("Kr",))
    st = TK._laser(1.9e7)
    steady = s30.solve_joint(st, 4.5, None, None, None, True)
    big = s30.step(st, steady, 1e3, target_mean=4.5, adapt=False)
    tiny = s30.step(st, steady, 1e-20, adapt=False)
    for key, sol in (("step.big", big), ("step.tiny", tiny)):
        n[key] = _e(float(np.max(np.abs(sol.F - steady.F))
                          / steady.F.max()))
    for cells, ee_on, key in ((600, False, "step.energy"),
                              (600, True, "step.ee600"),
                              (2400, True, "step.ee2400")):
        s = KB.Solver(procs, n_cells=cells, emax=30.0, elastic=("Kr",))
        stc = st if ee_on else KB.State(x=st.x, tg=st.tg, n_col=st.n_col,
                                        ne=0.0, pen=st.pen, rec=st.rec,
                                        rec_pow=st.rec_pow)
        g = s.grid
        F0 = g.maxwellian_at_mean(1.5 * KB.KB * st.tg / KB.QE)
        cold = KB.Solution(F0, 0.0, 0.0, g.mean(F0), False, 0, g)
        sol = s.step(stc, cold, 1e-12, target_power=1e9, adapt=False)
        gain, loss, _ = TK._energy(s, stc, sol, procs)
        rise = (sol.mean - cold.mean) / 1e-12
        n[key] = _e(abs(gain - loss - rise) / gain)
    n["step.power"] = "$10^{9}$"
    return n


def fast_numbers() -> tuple:
    """(numbers, tables)."""
    _ml()
    from ml import data, forward, params, score
    n = {}
    v02 = _v02_numbers()
    # ML's scorecard under v0_3, which must be v0_2's: these tests have
    # no electrons, and v0_3's chemistry is v0_2's
    c = forward.with_rederived_k_e(params.light_now())
    same = 0
    for ds in data.all_datasets():
        if ds.kind in data.DEVICE_KINDS:
            continue
        v = score.kinetic_score(ds, c)
        s = MO._pct_signed(v) if len(ds.values) == 1 else f"{v:.1f}"
        n[f"sc.{ds.name}"] = s
        if v02.get(f"sc.{ds.name}") != s:
            raise RuntimeError(f"{ds.name}: v0_3 scores {s}, v0_2 "
                               f"{v02.get(f'sc.{ds.name}')}: the tests "
                               "without electrons should not move")
        same += 1
    n["sc.same"] = str(same)
    rms = [score.kinetic_score(d, c) for d in data.by_role("train")
           if len(d.values) > 1]
    n["sc.train.lo"], n["sc.train.hi"] = f"{min(rms):.1f}", f"{max(rms):.1f}"
    for kr, meas in MO.XU_1993:
        n[f"xu.{kr:.0f}"] = MO._x(_krf_decay(kr, 1.0), meas)
        if n[f"xu.{kr:.0f}"] != v02[f"xu.{kr:.0f}"]:
            raise RuntimeError(f"Xu {kr} Torr: v0_3 {n[f'xu.{kr:.0f}']}, "
                               f"v0_2 {v02[f'xu.{kr:.0f}']}")
    n.update(_solver_checks())
    n.update(_constants())
    return n, []


