def _render(n: dict, what: str, tables=()) -> str:
    lines = [
        f"% LIGHT v0_3 accuracy numbers ({what}). GENERATED by "
        "make_overview_v0_3.py",
        f"% from LIGHT v0_3 ({__version__}) and ML/. Do not edit. Rerun the "
        "script instead.",
        r"\providecommand\wkdef[2]{\expandafter\def\csname wk@#1\endcsname{#2}}",
    ]
    lines += [f"\\wkdef{{{k}}}{{{v}}}" for k, v in n.items()]
    lines += list(tables)
    return "\n".join(lines) + "\n"


def _e(v: float, digits: int = 1) -> str:
    """A small number as 1.2e-5 in LaTeX: $1.2{\\times}10^{-5}$."""
    if v == 0.0:
        return "0"
    mant, ex = f"{v:.{digits}e}".split("e")
    return f"${mant}{{\\times}}10^{{{int(ex)}}}$"


