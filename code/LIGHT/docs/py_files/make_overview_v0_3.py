def _bands_of(res) -> dict:
    m, e = res.model, res.ledger["E_dep"][-1]
    rows = {x.rid: x for x in m.rows}
    return {k: 100.0 * res.events[rid][-1] * rows[rid].hv_eV / e
            for k, rid in BAND_ROWS.items()}


FIRST_NS = 1e-9                     # the window of the first nanosecond


def task_reference(eedf="kinetic", first_maxwell=False, **kw) -> dict:
    """The reference point: bands, totals, Tg, closure, flows, the
    electron log's checks, the kinetic rate factors mid-pulse, and the
    first nanosecond's updates. first_maxwell: LIGHT's own Maxwellian
    closure before FIRST_NS, the kinetic EEDF after."""
    from v0_3.model import Model, Params
    from v0_3.report import accounting, row_dict
    t0 = time.time()
    m = Model(Params(eedf=eedf, **kw))
    if first_maxwell:
        update = m._kinetic_update

        def maxwell_first(t, y, on):
            if t < FIRST_NS:
                m._tab = None
                m._kin_sol = None
                m._kin_ref = m._kin_observed(y)
                return None
            return update(t, y, on)
        m._kinetic_update = maxwell_first
    res = m.run()
    out = {"time": time.time() - t0, "bands": _bands_of(res),
           "row": {k: v for k, v in row_dict(res).items()
                   if isinstance(v, float)},
           "closure": accounting(res)["closure"]}
    if eedf == "kinetic":
        log = [e for e in res.kinetic if not e.get("skipped")]
        on = [e for e in log if e["on"]]
        late = [e for e in on if e["t"] >= 0.5 * m.p.pulse_s]
        first = [e for e in on if e["t"] < FIRST_NS]
        out.update(
            solutions=len(log), on=len(on),
            en=(min(e["en_td"] for e in on if e["en_td"] > 0.0),
                max(e["en_td"] for e in on)),
            ratio=[e["power_ratio"] for e in late
                   if np.isfinite(e["power_ratio"])],
            gap=max(abs(e["balance"]) for e in late),
            factors=_factors(m, log, 0.5 * m.p.pulse_s),
            first={"n": len(first),
                   "edep": float(np.interp(FIRST_NS, res.t,
                                           res.ledger["E_dep"])
                                 / res.ledger["E_dep"][-1]),
                   "goff": sum(e["growth_off"] for e in first),
                   "unreached": sum(not e["reached"] for e in first),
                   "ratio": [e["power_ratio"] for e in first
                             if np.isfinite(e["power_ratio"])],
                   "gap": [abs(e["balance"]) for e in first
                           if e["t"] > 0.1 * FIRST_NS],
                   "gap0": [abs(e["balance"]) for e in first
                            if e["t"] <= 0.1 * FIRST_NS]})
    return out


def _factors(m, log, t_mid) -> dict:
    """The kinetic rate of each electron row over LIGHT's Maxwellian rate
    at the same Te, at the update nearest t_mid."""
    e = min(log, key=lambda x: abs(x["t"] - t_mid))
    te = e["te"]
    n = np.zeros(m.ns)
    out = {"t": e["t"], "te": te}
    for c in m.compiled:
        if c.row.rid in e["k"]:
            k_m = m._k(c, te, 300.0, n, 1.0)
            out[c.row.rid] = e["k"][c.row.rid] / k_m if k_m > 0 else math.nan
    return out


def task_tahoma(I_MW=None, band=None, value=None, kannari=False,
                memory=None) -> dict:
    """Tahoma under the beam drive: with I_MW, ML's formation run (the
    gain at that probe flux); else the 200-400 ns window's g0, Tg, n_e, Te
    for v0_3's default, one band at value, or Kannari's two estimates.
    memory: kin_memory_s (0 is the steady EEDF throughout)."""
    _ml()
    from ml import forward, formation, params
    c = forward.with_rederived_k_e(params.light_now())
    t0 = time.time()
    if I_MW is not None:
        r = formation.run(c, formation.LIGHT_CHAIN, I_MW)
        return {"g": r["g"], "time": time.time() - t0,
                **({"formation": r["formation"], "tg": r["tg"]}
                   if I_MW == 0.0 else {})}
    p = forward.tahoma_params()
    if band is not None:
        p = (p.replace(trimer_tg_pow=value) if band == "trimer_tg_pow"
             else p.replace(rates=((band, value),)))
    if kannari:
        p = p.replace(rates=tuple((b, _kannari(b)) for b in ("kr2_f",
                                                              "kr2_pen")))
    if memory is not None:
        p = p.replace(kin_memory_s=memory)
    m = forward.impose(forward._drive().BeamModel(p), c)
    r = m.run()
    win = (r.t >= forward.WINDOW[0]) & (r.t <= forward.WINDOW[1])
    out = {"g0": forward.SIGMA_B * float(np.mean(r.n["KrF(B)"][win])) * 100,
           "tg": float(np.mean(r.tg[win])), "ne": float(np.mean(r.ne[win])),
           "te": float(np.mean(r.te[win])), "time": time.time() - t0}
    if band is None and not kannari:
        out["first_unreached"] = sum(
            not e["reached"] for e in r.kinetic
            if not e.get("skipped") and e["t"] < FIRST_NS)
    if band is None and not kannari and memory is None:
        log = [e for e in r.kinetic if not e.get("skipped")]
        inwin = [e for e in log if forward.WINDOW[0] <= e["t"]
                 <= forward.WINDOW[1]]
        out.update(gap=max(abs(e["balance"]) for e in inwin),
                   reached=all(e["reached"] for e in inwin),
                   en=max(e["en_td"] for e in inwin),
                   factors=_factors(m, log, 0.5 * sum(forward.WINDOW)))
    return out


def _kannari(band: str) -> float:
    """Kannari's estimate for an unmeasured Kr2* row (v0_1's kr2 group)."""
    return {"kr2_f": 3.0e-10, "kr2_pen": 5.0e-10}[band]


def task_loop() -> dict:
    """ML's self-consistent LIGHT-Boltzmann loop on v0_3's chemistry, and
    v0_3's own electrons under the same drive."""
    _ml()
    from ml import eedf, forward, params
    c = forward.with_rederived_k_e(params.light_now())
    loop, b, hist = eedf.self_consistent(c)
    own = forward.run_device(c)
    keys = ("te", "ne", "g0", "formation")
    return {"loop": {k: loop[k] for k in keys},
            "own": {k: own[k] for k in keys}, "passes": len(hist),
            "boltz_te": 2.0 / 3.0 * b["mean"]}


def task_pure(**kw) -> dict:
    _ml()
    from ml import pure
    t0 = time.time()
    r = pure.kr_vuv(**kw)
    return {"vuv": r["vuv"], "time": time.time() - t0}


